// Атырау облысындағы белгілі ірі өнеркәсіп эмиссия көздері.
// Координаттар — ашық, жалпыға қолжетімді деректер (шамамен, объектінің
// орталығы). Әр көздің "эмиссия профилі" — сол кәсіпорын сипаттамалы түрде
// қандай ластаушыны шығаратынын көрсетеді (0..1 салыстырмалы салмақ).
// Дереккөз: ашық өнеркәсіптік мәліметтер. Ойдан дерек жоқ.

export type PollutantKey = "so2" | "no2" | "pm" | "voc";

export interface Facility {
  id: string;
  name: string;
  short: string;
  lat: number;
  lng: number;
  kind: string; // сипаттама
  approx?: boolean; // координата жуық (нақты бекітілген дереккөз жоқ)
  /**
   * Нысан аумағының контуры [lng, lat] — OpenStreetMap (ODbL). Жылу
   * аномалиясы нысанға ТЕК осы контур + FOOTPRINT_BUFFER_KM ішінде болса
   * ғана телінеді. Контур жоқ нысанға телу ЖАСАЛМАЙДЫ.
   * Себебі: validation/firms — 10 км радиус ережесі АМӨЗ-ге телінген
   * детекциялардың 96%-ын қате телитін (дала/қамыс өрттері).
   */
  footprint?: [number, number][];
  footprintSource?: string;
  // Сипаттамалы эмиссия профілі (0..1): осы көз қай ластаушыны басым шығарады
  profile: Record<PollutantKey, number>;
}

