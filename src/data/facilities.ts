// орталығы). Әр көздің "эмиссия профилі" — сол кәсіпорын сипаттамалы түрде
// қандай ластаушыны шығаратынын көрсетеді (0..1 салыстырмалы салмақ).
// Дереккөз: ашық өнеркәсіптік мәліметтер. Ойдан дерек жоқ.

import type { Footprint } from "@/lib/footprint";

export type PollutantKey = "so2" | "no2" | "pm" | "voc";

/** Дереккөзі мен күні көрсетілген дерек. Екеуі де жоқ болса — қолданылмайды. */
export interface Cited {
  source: string;
  date: string;
}

/**
 * Нысанның расталған ашық деректері (P2.1). Бұл өріс ТЕК нақты, дереккөзі бар
 * мәндермен толтырылады. Жоқ болса — карточкада «Дерек жоқ» көрсетіледі.
 * ⚠️ Шығарынды саны (көздер саны) мен шығарынды массасы БӨЛЕК өрістер.
 */
export interface FacilityRecord {
  /** Шығарынды көздерінің саны (дана). Масса емес. */
  emissionSources?: Cited & { count: number };
  /** Шығарынды массасы — тек бірлік пен есептік кезеңімен бірге */
  emissionMass?: Cited & { value: number; unit: string; period: string };
  substances?: (Cited & { name: string; amount: number; unit: string; period: string })[];
  /** Рұқсат етілген (нормативтік) жылдық шығарынды — ЛИМИТ, нақты шығарынды ЕМЕС */
  emissionLimits?: (Cited & { period: string; value: number; unit: string })[];
  /** Зат бойынша рұқсат етілген жылдық шығарынды (НДВ жобасы) — ЛИМИТ, нақты емес */
  substanceLimits?: (Cited & { name: string; amount: number; unit: string; period: string })[];
  monitoringPosts?: (Cited & { name: string })[];
  verifiedEvents?: (Cited & { description: string })[];
}

export interface Facility {
  id: string;
  name: string;
  short: string;
  lat: number;
  lng: number;
  kind: string; // сипаттама
  approx?: boolean; // координата жуық (нақты бекітілген дереккөз жоқ)
  /**
   * Нысан аумағының тұйық контуры немесе бөлек сыртқы контурлары
   * [lng, lat] — OpenStreetMap (ODbL). Жылу
   * аномалиясы нысанға ТЕК осы контур + FOOTPRINT_BUFFER_KM ішінде болса
   * ғана телінеді. Контур жоқ нысанға телу ЖАСАЛМАЙДЫ.
   * Себебі: validation/firms — 10 км радиус ережесі АМӨЗ-ге телінген
   * детекциялардың 96%-ын қате телитін (дала/қамыс өрттері).
   */
  footprint?: Footprint;
  footprintSource?: string;
  // Сипаттамалы эмиссия профілі (0..1): осы көз қай ластаушыны басым шығарады
  /** Координатаның дереккөзі (атауы). Күні белгісіз болса — карточкада «Дерек жоқ». */
  coordSource?: string;
  /** Координатаның дереккөз күні. Нақты белгілі болмаса жазылмайды — карточкада «Дерек жоқ». */
  coordDate?: string;
  /** Расталған ашық деректер (P2.1). Бос — карточкада «Дерек жоқ». */
  record?: FacilityRecord;
  profile: Record<PollutantKey, number>;
}

