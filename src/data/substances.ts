//
// Расталған ШРК мәндері БӨЛЕК файлда — `legalNorms.ts`. Жаңа затқа норма
// қосу үшін актінің өз мәтінінен растау керек.

export type SubstanceStatus =
  /** Жүйеде тікелей өлшенеді (модель немесе станса) */
  | "measured"
  /** Тікелей емес — жанама көрсеткіш арқылы ғана байқалады */
  | "proxy"
  /** Мүлдем өлшенбейді — олқылық */
  | "not-measured";

