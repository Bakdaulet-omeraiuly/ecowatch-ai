/** Аймақтың шамамен ауданы (км²) — тек анықтама үшін, есептеу пиксельмен жүреді. */
export function zoneAreaKm2(z: FloodZone): number {
  const [w, s, e, n] = z.bbox;
  const midLat = ((s + n) / 2) * (Math.PI / 180);
  const kmPerDegLat = 111.32;
  const kmPerDegLng = 111.32 * Math.cos(midLat);
  return Math.round((e - w) * kmPerDegLng * (n - s) * kmPerDegLat);
}
