export function analyzeUserPrompt(mode: string): string {
  const science = `"science":{"ndvi":0-1,"ndbi":0-1,"ndwi":0-1,"areaM2":number,"changeDynamics":"суреттер арасындағы НАҚТЫ өзгеріс (жылдар берілсе) немесе «салыстыруға екінші кезең берілмеді»","nearbyInfrastructure":["суретте КӨРІНГЕН нысандар"],"textureNote":"...","evidence":[{"sign":"...","evidence":"қай сурет (нөмірі), қай бөлігі, қандай визуалды белгі","confidence":0-100,"prediction":"..."}]}`;
  const schema = `{"riskScore":0-100,"confidence":0-100,"oilPollution":bool,"illegalDumping":bool,"landDegradation":bool,"standingWater":bool,"detectedFeatures":["..."],"recommendation":"...","summary":"...",${science}}`;
  if (mode === "satellite")
    return `Берілген спутник суреттерін экологиялық тәуекелге талда. Масштабтарды салыстыр, жылдар берілсе өзгерісті анықта. JSON: ${schema}`;
  if (mode === "photo")
    return `Азамат түсірген жер деңгейіндегі осы фотоны талда: қоқыс түрі, көлемі, қауіптілігі. JSON: ${schema}`;
  return `Алдымен азаматтың жердегі фотосы, содан кейін сол координаттың спутник көріністері беріледі. Спутник көрінісі жердегі дәлелді растай ма? JSON: ${schema} + "verificationStatus":"confirmed|unconfirmed|contradicted","verificationNotes":"..."`;
}

